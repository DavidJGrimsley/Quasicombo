inline bool TryGetQuasicomboBraidFixture(const TArray<EQuasicomboLane>& History,
	FQuasicomboBraidFixture& OutFixture)
{
	if (History.Num() != 3) return false;
	int32 Index = 0;
	for (EQuasicomboLane Lane : History)
	{
		const int32 LaneIndex = static_cast<int32>(Lane);
		if (LaneIndex < 0 || LaneIndex > 2) return false;
		Index = Index * 3 + LaneIndex;
	}
	OutFixture = GQuasicomboBraidFixtures[Index];
	return true;
}
